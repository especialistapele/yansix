-- YANSIX Clínica: extensões de schema e RLS.
-- Executar após crm_yansix/sql/clinic_crm_foundation.sql.
-- Todas as tabelas são isoladas por clinic_id e usam RLS.

alter table public.clinic_crm_members add column if not exists display_name text;
alter table public.clinic_crm_members add column if not exists email text;
create index if not exists clinic_crm_members_clinic_role_idx on public.clinic_crm_members(clinic_id, role, active);

do $$
begin
  if not exists (select 1 from pg_constraint where conname='clinic_crm_opportunities_clinic_id_id_key') then
    alter table public.clinic_crm_opportunities add constraint clinic_crm_opportunities_clinic_id_id_key unique (clinic_id,id);
  end if;
end $$;

create table if not exists public.clinic_crm_quotes (
  id uuid primary key default gen_random_uuid(),
  clinic_id uuid not null references public.clinic_crm_clinics(id) on delete cascade,
  contact_id uuid not null,
  opportunity_id uuid,
  quote_number bigint generated by default as identity,
  title text not null,
  items jsonb not null default '[]'::jsonb,
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  status text not null default 'draft' check (status in ('draft','sent','approved','rejected','expired')),
  valid_until date,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint clinic_crm_quotes_contact_tenant_fkey foreign key (clinic_id, contact_id) references public.clinic_crm_contacts(clinic_id,id) on delete restrict,
  constraint clinic_crm_quotes_opportunity_tenant_fkey foreign key (clinic_id, opportunity_id) references public.clinic_crm_opportunities(clinic_id,id) on delete restrict,
  constraint clinic_crm_quotes_clinic_id_id_key unique (clinic_id,id),
  constraint clinic_crm_quotes_subtotal_discount_check check (discount <= subtotal)
);
create index if not exists clinic_crm_quotes_clinic_created_idx on public.clinic_crm_quotes(clinic_id, created_at desc);
alter table public.clinic_crm_quotes enable row level security;
drop policy if exists clinic_crm_quotes_access on public.clinic_crm_quotes;
drop policy if exists clinic_crm_quotes_select on public.clinic_crm_quotes;
drop policy if exists clinic_crm_quotes_insert on public.clinic_crm_quotes;
drop policy if exists clinic_crm_quotes_update on public.clinic_crm_quotes;
drop policy if exists clinic_crm_quotes_delete on public.clinic_crm_quotes;
create policy clinic_crm_quotes_select on public.clinic_crm_quotes for select to authenticated using (public.clinic_crm_has_access(clinic_id));
create policy clinic_crm_quotes_insert on public.clinic_crm_quotes for insert to authenticated with check (public.clinic_crm_has_access(clinic_id, array['owner','admin','manager','reception']) and (created_by is null or created_by=auth.uid()));
create policy clinic_crm_quotes_update on public.clinic_crm_quotes for update to authenticated using (public.clinic_crm_has_access(clinic_id, array['owner','admin','manager','reception'])) with check (public.clinic_crm_has_access(clinic_id, array['owner','admin','manager','reception']));
create policy clinic_crm_quotes_delete on public.clinic_crm_quotes for delete to authenticated using (public.clinic_crm_has_access(clinic_id, array['owner','admin','manager']));

create table if not exists public.clinic_crm_finance_entries (
  id uuid primary key default gen_random_uuid(),
  clinic_id uuid not null references public.clinic_crm_clinics(id) on delete cascade,
  contact_id uuid,
  quote_id uuid,
  entry_type text not null check (entry_type in ('income','expense')),
  category text not null default 'other',
  description text not null,
  amount numeric(12,2) not null check (amount > 0),
  due_date date,
  paid_at timestamptz,
  payment_method text,
  status text not null default 'pending' check (status in ('pending','paid','cancelled')),
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint clinic_crm_finance_contact_tenant_fkey foreign key (clinic_id, contact_id) references public.clinic_crm_contacts(clinic_id,id) on delete restrict,
  constraint clinic_crm_finance_quote_tenant_fkey foreign key (clinic_id, quote_id) references public.clinic_crm_quotes(clinic_id,id) on delete restrict
);
create index if not exists clinic_crm_finance_clinic_due_idx on public.clinic_crm_finance_entries(clinic_id, due_date desc);
