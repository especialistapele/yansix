create table if not exists public.clinic_crm_quotes (
  id uuid primary key default gen_random_uuid(),
  clinic_id uuid not null references public.clinic_crm_clinics(id) on delete cascade,
  contact_id uuid not null,
  opportunity_id uuid,
  quote_number bigint generated by default as identity,
  title text not null,
  items jsonb not null default '[]'::jsonb,
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  status text not null default 'draft' check (status in ('draft','sent','approved','rejected','expired')),
  valid_until date,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint clinic_crm_quotes_contact_tenant_fkey foreign key (clinic_id, contact_id) references public.clinic_crm_contacts(clinic_id,id) on delete restrict,
  constraint clinic_crm_quotes_opportunity_tenant_fkey foreign key (clinic_id, opportunity_id) references public.clinic_crm_opportunities(clinic_id,id) on delete restrict,
  constraint clinic_crm_quotes_clinic_id_id_key unique (clinic_id,id),
  constraint clinic_crm_quotes_subtotal_discount_check check (discount <= subtotal)
);
create index if not exists clinic_crm_quotes_clinic_created_idx on public.clinic_crm_quotes(clinic_id, created_at desc);
alter table public.clinic_crm_quotes enable row level security;
